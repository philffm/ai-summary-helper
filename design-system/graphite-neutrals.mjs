#!/usr/bin/env node
// Graphite: the colour scheme with no hue. The brand ramp alone is not enough: the app's neutrals (page and card backgrounds, text, borders,
// tracks) are the blue-tinted Slate scale and the blue-black Night 950, so a grey accent on them still looks blue.
//   node design-system/graphite-neutrals.mjs     (re-run after the Slate scale or a token that uses it changes; the output is committed)
// Writes the colour.mono.* primitives (the same lightness as each Slate step / Night 950, almost no chroma) and the token sets
// app/graphite-light and app/graphite-dark: every token of the standard light / dark sets that reads a Slate / Night colour, pointing at its
// mono twin instead. The Graphite scheme blocks in config.json add these sets.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const DS = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(fs.readFileSync(path.join(DS, f), 'utf8'));
const write = (f, o) => fs.writeFileSync(path.join(DS, f), JSON.stringify(o, null, 2) + '\n');

// ── the mono primitives
const hexToRgb = (h) => { const n = parseInt(h.slice(1), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const hslToHex = (h, s, l) => { const a = s * Math.min(l, 1 - l); const f = (n) => { const k = (n + h / 30) % 12; return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); }; return '#' + [f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, '0')).join('').toUpperCase(); };
const lightness = (hex) => { const [r, g, b] = hexToRgb(hex).map((x) => x / 255); return (Math.max(r, g, b) + Math.min(r, g, b)) / 2; };
const mono = (hex) => hslToHex(30, 0.03, lightness(hex));   // warm graphite grey: hue 30°, 3 % saturation, the same lightness
const colorFile = read('tokens/primitive/color.json');
const group = { $type: 'color', $description: 'Graphite scheme neutrals: each Slate step and Night 950 with its hue taken out (same lightness, 3 % warm). Generated by design-system/graphite-neutrals.mjs.' };
for (const [k, v] of Object.entries(colorFile.color.slate)) if (!k.startsWith('$') && v.$value) group['slate-' + k] = { $value: mono(v.$value) };
group['night-950'] = { $value: mono(colorFile.color.night['950'].$value) };
colorFile.color.mono = group;
write('tokens/primitive/color.json', colorFile);

// ── the token sets
const REF = /\{color\.(slate|night)\.(\w+)(@[\d.]+)?\}/g;
const swapRefs = (s) => String(s).replace(REF, (_, g, n, a) => `{color.mono.${g}-${n}${a || ''}}`);
const collect = (setFiles) => {
  const out = {};
  for (const f of setFiles) {
    const walk = (o, trail) => { for (const [k, v] of Object.entries(o)) {
      if (k.startsWith('$')) continue;
      if (v && v.$value !== undefined) { if (REF.test(String(v.$value))) { REF.lastIndex = 0; let t = out; trail.forEach((p) => { t = t[p] ??= {}; }); t[k] = { ...v, $value: swapRefs(v.$value) }; } REF.lastIndex = 0; }
      else if (v && typeof v === 'object') walk(v, [...trail, k]); } };
    walk(read(f), []);
  }
  return out;
};
const count = (o) => Object.values(o).reduce((n, v) => n + (v && v.$value !== undefined ? 1 : count(v)), 0);
const light = collect(['tokens/app/base.json', 'tokens/app/light.json']);
const dark = collect(['tokens/app/dark.json', 'tokens/app/dark-forced.json']);
const hcLight = collect(['tokens/app/contrast.json']), hcDark = collect(['tokens/app/contrast-dark.json']);   // High contrast with Graphite: its few slate greys too
write('tokens/app/graphite-light.json', light); write('tokens/app/graphite-dark.json', dark);
write('tokens/app/graphite-contrast.json', hcLight); write('tokens/app/graphite-contrast-dark.json', hcDark);
console.log(`graphite neutrals: ${Object.keys(group).length - 2} primitives, ${count(light)} light and ${count(dark)} dark tokens`);
