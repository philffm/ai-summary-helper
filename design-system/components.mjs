#!/usr/bin/env node
// design-system/components.mjs — component manifest (ADR 0005).
//   node design-system/components.mjs           write dist/components.json + dist/components.md
//   node design-system/components.mjs --check   fail if a selector, source file or semantic description is missing, or dist is stale
// Source: design-system/components.json (hand-edited). Added here, from the code: the tokens each component reads
// (var(--x) in every CSS rule whose selector names one of the component's classes), so the list cannot go stale.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DS = dirname(fileURLToPath(import.meta.url));
const ROOT = join(DS, '..');
const check = process.argv.includes('--check');
const problems = [];
const src = JSON.parse(readFileSync(join(DS, 'components.json'), 'utf8'));
const css = readFileSync(join(ROOT, 'plugin/src/styles.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// every CSS rule (inner rules of @media/@supports included), as [selector, body]
const rules = [];
for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) rules.push([m[1].trim(), m[2]]);

// tokens defined anywhere (resolved, every brand × context × mode)
const resolved = JSON.parse(readFileSync(join(DS, 'dist/tokens.resolved.json'), 'utf8'));
const defined = new Set();
const collect = (o) => { for (const [k, v] of Object.entries(o || {})) { if (k.startsWith('--')) defined.add(k); else if (v && typeof v === 'object') collect(v); } };
collect(resolved);

// the class or id a selector stands for: '.mcp-card[role=alert]' -> '.mcp-card', 'progress.sync-progress' -> '.sync-progress'
const anchors = (sel) => (sel.match(/[.#][A-Za-z_][\w-]*/g) || []);
const re = (a) => new RegExp(a.replace(/[.#]/, (c) => '\\' + c) + '(?![\\w-])');

const components = src.components.map((c) => {
  const tokens = new Set();
  for (const sel of c.selectors) {
    const as = anchors(sel);
    if (!as.length) { problems.push(`${c.name}: selector "${sel}" has no class or id`); continue; }
    const hits = rules.filter(([s]) => as.every((a) => re(a).test(s)));
    if (!hits.length) problems.push(`${c.name}: no CSS rule for "${sel}" in plugin/src/styles.css`);
    for (const [, body] of hits) for (const m of body.matchAll(/var\((--[\w-]+)/g)) if (defined.has(m[1])) tokens.add(m[1]);
  }
  for (const f of c.source) if (!existsSync(join(ROOT, f))) problems.push(`${c.name}: source ${f} does not exist`);
  if (!c.figma || !c.figma.node) problems.push(`${c.name}: no Figma node`);
  if (!c.purpose) problems.push(`${c.name}: no purpose`);
  if (!c.a11y || !c.a11y.length) problems.push(`${c.name}: no a11y notes`);
  return { ...c, tokens: [...tokens].sort() };
});

// every semantic token has a $description in at least one mode file
const described = new Map();
const files = [];
const walkDir = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walkDir(p); else if (f.endsWith('.json')) files.push(p); } };
walkDir(join(DS, 'tokens'));
for (const f of files) {
  const j = JSON.parse(readFileSync(f, 'utf8'));
  for (const [ctx, body] of Object.entries(j)) {
    if (ctx.startsWith('$') || !body || !body.semantic) continue;
    const walk = (o) => { for (const [k, v] of Object.entries(o)) { if (k.startsWith('$') || !v || typeof v !== 'object') continue; if ('$value' in v) { const key = ctx + ':' + k; described.set(key, described.get(key) || !!v.$description); } else walk(v); } };
    walk(body.semantic);
  }
}
const undescribed = [...described].filter(([, d]) => !d).map(([k]) => k);
for (const k of undescribed) problems.push(`semantic token ${k} has no $description`);

// outputs
const json = JSON.stringify({ $description: 'Generated by design-system/components.mjs from design-system/components.json and plugin/src/styles.css. Do not edit.', components }, null, 2) + '\n';
const md = ['# AISH components', '', 'Generated from `design-system/components.json` and `plugin/src/styles.css` by `design-system/components.mjs`. Do not edit. Figma: Library v3 on the Components page of the AISH file.', ''];
for (const c of components) {
  md.push(`## ${c.name}`, '', `Status: ${c.status} · Figma node ${c.figma.node}`, '', c.purpose, '');
  md.push(`- CSS: ${c.selectors.map((s) => '`' + s + '`').join(', ')}`);
  md.push(`- Source: ${c.source.map((s) => '`' + s + '`').join(', ')}`);
  const v = Object.entries(c.variants); if (v.length) md.push(`- Variants: ${v.map(([k, o]) => `${k} (${o.join(' / ')})`).join(' · ')}`);
  const p = Object.entries(c.props); if (p.length) md.push(`- Properties: ${p.map(([k, o]) => `${k} (${o.type.toLowerCase()})`).join(', ')}`);
  if (c.tokens.length) md.push(`- Tokens: ${c.tokens.map((t) => '`' + t + '`').join(', ')}`);
  md.push('- Accessibility:', ...c.a11y.map((a) => `  - ${a}`));
  if (c.do.length) md.push('- Do:', ...c.do.map((a) => `  - ${a}`));
  if (c.dont.length) md.push("- Don't:", ...c.dont.map((a) => `  - ${a}`));
  md.push('');
}
const outJ = join(DS, 'dist/components.json'), outM = join(DS, 'dist/components.md');
if (check) {
  if (!existsSync(outJ) || readFileSync(outJ, 'utf8') !== json) problems.push('dist/components.json is out of date: run npm run components');
  if (!existsSync(outM) || readFileSync(outM, 'utf8') !== md.join('\n')) problems.push('dist/components.md is out of date: run npm run components');
} else { writeFileSync(outJ, json); writeFileSync(outM, md.join('\n')); }
if (problems.length) { for (const p of problems) console.error('✗ ' + p); console.error(`\n${problems.length} problem(s)`); process.exit(1); }
console.log(`✓ components ${check ? 'checked' : 'written'}: ${components.length} components, ${components.reduce((n, c) => n + c.tokens.length, 0)} token reads, ${described.size} semantic tokens described`);
