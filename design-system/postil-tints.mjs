#!/usr/bin/env node
// Postil with a light tint of a brand colour (Design Postil + Color scheme Kaivo / Aish / Viola).
//   node design-system/postil-tints.mjs      (re-run after changing TINT below; the output is committed)
// Writes, from the brand's own accent ramp and the Postil paper / charcoal scale:
//   - brand.postil.* primitives in tokens/primitive/brand/<brand>.json (the tinted papers, charcoals and the accent)
//   - tokens/app/postil-tint.json and postil-tint-dark.json: the Postil tokens that change, as references to those primitives
// Text stays Postil's graphite ink; surfaces take a few percent of the brand colour, the accent is the brand's own (checked for AA by the gate).
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
const DS = path.dirname(fileURLToPath(import.meta.url));
const read = (f) => JSON.parse(fs.readFileSync(path.join(DS, f), 'utf8'));
const write = (f, o) => fs.writeFileSync(path.join(DS, f), JSON.stringify(o, null, 2) + '\n');

// how much of the brand colour goes into each Postil surface: the pale tint (accent 100) into the papers, the accent itself (500) into the
// charcoals. A pale tint keeps the paper light (the mid-tone accent would darken it).
const TINT = { light: { 'paper-50': 0.15, 'paper-100': 0.22, 'paper-150': 0.28, 'paper-200': 0.36, 'paper-300': 0.38 },
               dark: { 'char-950': 0.06, 'char-900': 0.07, 'char-850': 0.08, 'char-800': 0.09, 'char-700': 0.10 } };
const BASE = { 'paper-50': 'paper.50', 'paper-100': 'paper.100', 'paper-150': 'paper.150', 'paper-200': 'paper.200', 'paper-300': 'paper.300',
               'char-950': 'char.950', 'char-900': 'char.900', 'char-850': 'char.850', 'char-800': 'char.800', 'char-700': 'char.700' };

const colours = (() => { const out = {}; const walk = (o, p) => { for (const [k, v] of Object.entries(o)) { if (k.startsWith('$')) continue; if (v && v.$value !== undefined) out[p + k] = v.$value; else if (v && typeof v === 'object') walk(v, p + k + '.'); } }; walk(read('tokens/primitive/color.json'), ''); return out; })();
const hex = (c) => { const m = /^#([0-9a-f]{6})$/i.exec(c); const n = parseInt(m[1], 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const toHex = (r) => '#' + r.map((x) => Math.round(x).toString(16).padStart(2, '0')).join('').toUpperCase();
const mix = (a, b, t) => toHex(hex(a).map((x, i) => x * (1 - t) + hex(b)[i] * t));
const baseColour = (id) => colours[BASE[id].startsWith('paper') || BASE[id].startsWith('char') ? 'color.' + BASE[id] : BASE[id]] ?? colours[BASE[id]];

const brands = fs.readdirSync(path.join(DS, 'tokens/primitive/brand')).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5));
for (const b of brands) {
  const file = `tokens/primitive/brand/${b}.json`, d = read(file);
  const acc = (n) => d.brand.accent[n].$value;
  const g = { $type: 'color', $description: 'Postil tinted with this brand (Design Postil + a colour scheme): the Postil papers and charcoals with a few percent of the accent, and the accent itself. Generated by design-system/postil-tints.mjs.' };
  for (const [id, t] of Object.entries(TINT.light)) g[id] = { $value: mix(baseColour(id), acc(100), t) };
  for (const [id, t] of Object.entries(TINT.dark)) g[id] = { $value: mix(baseColour(id), acc(500), t) };
  g.accent = { $value: acc('contrast') };        // light: dark enough for white text and for links on the tinted paper
  g['accent-dark'] = { $value: acc(200) };       // dark: light enough for the charcoal text on it
  d.brand.postil = g;
  write(file, d);
}

// the Postil tokens that change, as references: copy from postil.json / postil-dark.json and swap the referenced primitive
const swap = (src, map) => {
  const out = { app: { semantic: {}, component: {} } };
  const walk = (o, p, into) => { for (const [k, v] of Object.entries(o)) {
    if (v && v.$value !== undefined) { const m = /^\{color\.(.+)\}$/.exec(String(v.$value)); if (m && map[m[1]]) { (into[p] ??= {})[k] = { ...v, $value: `{brand.postil.${map[m[1]]}}`, ...(v.$description ? { $description: String(v.$description).replace('graphite accent, the same in every brand', "the colour scheme's own accent").replace('Postil scheme', 'Postil with a colour scheme') } : {}) }; } }
    else if (v && typeof v === 'object') walk(v, k, into); } };
  const sem = {}; walk(src.app.semantic, '', sem);
  for (const [grp, toks] of Object.entries(sem)) out.app.semantic[grp] = toks;
  return out;
};
const light = swap(read('tokens/app/postil.json'), { 'paper.50': 'paper-50', 'paper.100': 'paper-100', 'paper.150': 'paper-150', 'paper.200': 'paper-200', 'paper.300': 'paper-300', 'cocoa.600': 'accent', 'cocoa.700': 'accent' });
// keep the sent-tone text graphite: it sits on a tinted paper but needs no brand colour
delete light.app.semantic.status?.['tone-sent-fg'];
const dark = swap(read('tokens/app/postil-dark.json'), { 'char.950': 'char-950', 'char.900': 'char-900', 'char.850': 'char-850', 'char.800': 'char-800', 'char.700': 'char-700', 'bone.200': 'accent-dark' });
for (const f of [light, dark]) { for (const g of Object.keys(f.app.semantic)) if (!Object.keys(f.app.semantic[g]).length) delete f.app.semantic[g]; }
write('tokens/app/postil-tint.json', light); write('tokens/app/postil-tint-dark.json', dark);
const n = (o) => Object.values(o.app.semantic).reduce((s, g) => s + Object.keys(g).length, 0);
console.log(`postil tints: ${brands.length} brands, ${n(light)} light and ${n(dark)} dark tokens`);
