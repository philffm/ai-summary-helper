#!/bin/bash
# Writes Config/Version.xcconfig from the repo's single version source. Build number as on Android: 2.2.57 -> 20257.
set -euo pipefail
IOS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION=$(sed -nE 's/^[[:space:]]*"version":[[:space:]]*"([0-9.]+)".*/\1/p' "$IOS/../../current_version.json" | head -1)
[ -n "$VERSION" ] || { echo "no version in current_version.json" >&2; exit 1; }
CODE=$(echo "$VERSION" | awk -F. '{ printf "%d", $1*10000 + $2*100 + $3 }')
printf '// generated by scripts/version.sh\nMARKETING_VERSION = %s\nCURRENT_PROJECT_VERSION = %s\n' "$VERSION" "$CODE" > "$IOS/Config/Version.xcconfig"
echo "version $VERSION ($CODE)"
