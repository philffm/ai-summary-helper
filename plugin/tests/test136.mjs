// Read mode page (readerPage.html/js): sanitized text, summary + highlights, reading prefs persisted, missing article.
import { setup, imp, tick } from './harness.mjs'; import assert from 'assert'; import fs from 'fs';
const { store, w } = setup({});
const { SK, articleRecKey } = await imp('../src/modules/storageKeys.js');
const page = fs.readFileSync(new URL('../src/readerPage.html', import.meta.url), 'utf8');
assert(!/<script(?![^>]*\bsrc=)/i.test(page), 'no inline script (extension CSP)');
w.document.documentElement.innerHTML = page.replace(/^[\s\S]*?<html[^>]*>/i, '').replace(/<\/html>[\s\S]*$/i, '');
const url = 'https://example.com/post';
store[SK.annotations] = [{ url, text: 'important sentence here', type: 'user', timestamp: new Date().toISOString() }];
const art = { id: 'a1', url, title: 'Hello <b>World</b>', timestamp: new Date().toISOString(), summary: '<p>Short summary</p>', content: '<h2>One</h2><p>An important sentence here and more.</p><h2>Two</h2><h3>Three</h3><script>alert(1)</script><img src="x" onerror="alert(1)"><a href="javascript:alert(1)">bad</a>' };
store['articles:index'] = [{ id: 'a1', url, title: art.title, timestamp: art.timestamp }];
store[articleRecKey('a1')] = art;
w.location.hash = '#id=a1';
await imp('../src/readerPage.js'); await tick(150);
const d = w.document;
const title = d.querySelector('.rp-title');
assert(title, 'article rendered');
assert.equal(title.textContent, 'Hello <b>World</b>', 'title is text, not markup');
assert(!/alert/.test(d.querySelector('.rp-content').innerHTML), 'script removed');
assert(!d.querySelector('[onerror]'), 'handlers removed');
assert(![...d.querySelectorAll('a')].some(a => /^javascript:/i.test(a.getAttribute('href') || '')), 'javascript: links removed');
assert(d.querySelector('.rp-content mark'), 'highlight marked in the text');
assert(d.querySelector('.rp-toc'), 'contents for 3+ headings');
d.getElementById('rpLarger').click(); d.querySelector('[data-theme="dark"]').click();
assert.equal(d.documentElement.dataset.rpTheme, 'dark');
assert.equal(store['reader:prefs'].size, 3); assert.equal(store['reader:prefs'].theme, 'dark');
d.querySelector('[data-view="summary"]').click();
assert.equal(d.documentElement.dataset.rpView, 'summary');
console.log('TEST 136 OK');
