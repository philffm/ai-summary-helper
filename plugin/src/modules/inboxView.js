// modules/inboxView.js
// The phone inbox in the popup: the Settings panel (pair with a QR code, status, unpair) and the "From phone" list at the
// top of History (Summarize / Dismiss). All state lives in storage (see inboxManager.js); this file only renders it.
import qrcode from '../lib/qrcode.js';
import { T } from './feedI18n.js';
import { SK } from './storageKeys.js';
import { createInboxManager } from './inboxManager.js';
import { setLabel, setIconLabel } from './icons.js';
import { normalizeUrl } from './textUtils.js';

const $ = (id) => document.getElementById(id);
const manager = createInboxManager();
let showCode = false;
let busy = '';
let message = '';
let confirmUnpair = false;

const ERRORS = () => ({
    unreachable: T("Can't reach byPhil Cloud right now."),
    'pairing-invalid': T('This pairing is no longer valid. Unpair and pair again.'),
    'rate-limited': T('Too many requests. Try again later.'),
    error: T('Something went wrong.'),
});
const errorText = (code) => (ERRORS()[code] || ERRORS().error);

function button(label, cls, onClick, disabled) {
    const b = document.createElement('button');
    b.type = 'button'; b.className = cls; b.textContent = label; b.disabled = !!disabled;
    b.addEventListener('click', onClick);
    return b;
}
function para(text, cls = 'setting-note') {
    const p = document.createElement('p'); p.className = cls; p.textContent = text; return p;
}

function qrBox(payload) {
    const q = qrcode(0, 'M');
    q.addData(payload); q.make();
    const box = document.createElement('div');
    box.className = 'phone-inbox-qr';
    box.innerHTML = q.createSvgTag({ cellSize: 4, margin: 2, scalable: true });   // generated by the library from our own payload, no page content
    const svg = box.querySelector('svg');
    if (svg) { svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', T('Pairing code')); }
    return box;
}

let settingsToken = 0;
async function renderSettings() {
    const root = $('phoneInboxSettings');
    if (!root) return;
    // Several things ask for a render at once (the click, storage.onChanged, the poll). Build the panel off-screen and
    // swap it in only if no newer render started meanwhile; clearing early and appending after an await doubled the QR.
    const token = ++settingsToken;
    const st = await manager.status();
    const frag = document.createDocumentFragment();
    frag.append(para(T('Install the AISH companion on your phone, scan the code once, then share any link to it. Links arrive end-to-end encrypted and wait here for your tap.')));

    if (!st.paired) {
        frag.append(button(busy === 'pair' ? T('Pairing…') : T('Pair a phone'), 'button-primary w-full', pair, !!busy));
    } else {
        const when = st.lastPollAt ? new Date(st.lastPollAt).toLocaleString() : '';
        frag.append(para(when ? T('Paired · last checked {when}', { when }) : T('Paired · not checked yet'), 'setting-note phone-inbox-status'));
        if (st.lastError) frag.append(para(errorText(st.lastError), 'setting-note phone-inbox-error'));
        if (showCode) {
            const payload = await manager.pairingCode();
            if (payload) {
                frag.append(qrBox(payload));
                frag.append(para(T('Scan this code with the AISH companion app. Anyone who scans it can send links to you, so keep it private.')));
            }
        }
        const row = document.createElement('div');
        row.className = 'phone-inbox-actions';
        row.append(
            button(showCode ? T('Hide code') : T('Show code'), 'button-secondary', () => { showCode = !showCode; renderSettings(); }),
            button(busy === 'poll' ? T('Checking…') : T('Check now'), 'button-secondary', checkNow, !!busy),
            button(confirmUnpair ? T('Click again to unpair') : T('Unpair and delete inbox'), 'button-danger btn-sm', unpair, !!busy),
        );
        frag.append(row);
        if (confirmUnpair) frag.append(para(T('Links still waiting here are deleted and the phone can no longer send.')));
    }
    if (message) frag.append(para(message, 'setting-note phone-inbox-error'));
    if (token !== settingsToken) return;   // a newer render is on its way; it will replace the panel
    root.replaceChildren(frag);
    const sub = document.querySelector('.settings-row-sub[data-sub="phoneinbox"]');
    if (sub && st.paired) sub.textContent = st.pending ? T('Paired · {n} waiting', { n: st.pending }) : T('Paired');
}

async function pair() {
    busy = 'pair'; message = ''; await renderSettings();
    const r = await manager.pair();
    busy = '';
    if (r.ok) showCode = true; else message = errorText(r.error);
    await renderSettings();
}
async function checkNow() {
    busy = 'poll'; message = ''; await renderSettings();
    const r = await manager.poll();
    busy = '';
    if (!r.ok && r.error !== 'not-paired') message = errorText(r.error);
    await renderSettings(); await renderList();
}
async function unpair() {
    if (!confirmUnpair) { confirmUnpair = true; await renderSettings(); setTimeout(() => { if (confirmUnpair) { confirmUnpair = false; renderSettings(); } }, 6000); return; }
    confirmUnpair = false; showCode = false; message = '';
    await manager.unpair();
    await renderSettings(); await renderList();
}

// ── History: links waiting for the user ──
function shortLink(url) {
    try { const u = new URL(url); return { host: u.hostname.replace(/^www\./, ''), path: (u.pathname + u.search).replace(/\/$/, '') }; } catch (_) { return { host: url, path: '' }; }
}

// Summarize: same behaviour as a feed card (feedManager.js): the button turns into a progress ring, waits in the
// summary queue when another one is running, and the link leaves the list once its summary exists.
const sumBusy = new Map();   // entry.id -> { pct, key, queued, jobId, timer }
const sumErrors = new Map(); // entry.id -> last error text (shown under the link until the next try)

function paintSum(id) {
    const st = sumBusy.get(id);
    const queued = !!(st && st.queued);
    document.querySelectorAll('#phoneInbox .feed-sum-btn').forEach((b) => {
        if (b.dataset.id !== id) return;
        b.classList.toggle('busy', !!st);
        b.disabled = !!st && !queued;   // a queued one can be clicked to leave the queue again
        b.setAttribute('aria-busy', st ? 'true' : 'false');
        if (queued) {
            b.style.removeProperty('--p'); b.removeAttribute('aria-valuenow'); b.removeAttribute('role');
            setLabel(b, T('⏳ Queued')); b.title = T('Waiting for the running summary — click to remove from the queue');
            return;
        }
        b.removeAttribute('title');
        if (st) {
            b.style.setProperty('--p', String(st.pct));
            setLabel(b, T('⏳ {n}%', { n: Math.round(st.pct) }));
            b.setAttribute('role', 'progressbar'); b.setAttribute('aria-valuenow', String(Math.round(st.pct)));
        } else {
            b.style.removeProperty('--p'); b.removeAttribute('aria-valuenow'); b.removeAttribute('role');
            setLabel(b, T('✨ Summarize'));
        }
    });
}
function endSum(id) {
    const st = sumBusy.get(id); if (!st) return;
    clearTimeout(st.timer); sumBusy.delete(id); paintSum(id);
}
function armSum(id, ms) {
    const st = sumBusy.get(id); if (!st) return;
    clearTimeout(st.timer); st.timer = setTimeout(() => endSum(id), ms);   // safety net
}

async function summarize(entry) {
    const q = sumBusy.get(entry.id);
    if (q && q.queued) {   // waiting in line: take it out again
        chrome.runtime.sendMessage({ action: 'cancelQueuedSummary', id: q.jobId }, () => { void chrome.runtime.lastError; });
        endSum(entry.id); return;
    }
    const { host } = shortLink(entry.url);
    sumErrors.delete(entry.id);
    sumBusy.set(entry.id, { pct: 5, key: normalizeUrl(entry.url), queued: false, jobId: null, timer: null });
    armSum(entry.id, 5 * 60 * 1000);
    paintSum(entry.id);
    const hide = () => $('phoneInbox') && $('phoneInbox').querySelectorAll('.phone-inbox-error').forEach(e => { if (e.dataset.id === entry.id) e.remove(); });
    hide();
    let res = null;
    try { res = await chrome.runtime.sendMessage({ action: 'openFeedItem', url: entry.url, title: host, summarize: true }); } catch (_) { /* background asleep: the link stays in the list */ }
    if (!res || !res.success) { endSum(entry.id); return; }
    if (res.mode !== 'extension') {   // inline mode: the page shows the summary itself, nothing to track here
        endSum(entry.id);
        await manager.resolve(entry.id); await renderList();
        return;
    }
    const st = sumBusy.get(entry.id);
    if (st) { st.jobId = res.id == null ? null : res.id; st.queued = !!res.queued; if (st.queued) armSum(entry.id, 60 * 60 * 1000); paintSum(entry.id); }
}

// Save only: keep the page in History without the AI (same as the Summarize screen's "Save only"), then the link is done.
const saving = new Set();
async function saveOnly(entry) {
    if (saving.has(entry.id) || sumBusy.has(entry.id)) return;
    saving.add(entry.id); sumErrors.delete(entry.id);
    paintSaving(entry.id);
    let res = null;
    try { res = await chrome.runtime.sendMessage({ action: 'saveFeedItem', url: entry.url }); } catch (_) { /* background asleep */ }
    saving.delete(entry.id);
    if (res && res.success) { await manager.resolve(entry.id); await renderList(); return; }
    const why = res && res.error;
    sumErrors.set(entry.id, why === 'empty' ? T("This page has no text to save.")
        : why === 'unreachable' ? T("The page didn't respond (blocked, or it needs a login). Open it and try again.")
        : T("Couldn't save this page. Open it once and try again."));
    await renderList();
}
function paintSaving(id) {
    document.querySelectorAll('#phoneInbox .phone-inbox-save').forEach((b) => {
        if (b.dataset.id !== id) return;
        const on = saving.has(id);
        b.disabled = on; b.setAttribute('aria-busy', on ? 'true' : 'false');
        setIconLabel(b, on ? 'loader' : 'download', on ? T('Saving…') : T('Save only'));
    });
    document.querySelectorAll('#phoneInbox .feed-sum-btn').forEach((b) => { if (b.dataset.id === id && !sumBusy.has(id)) b.disabled = saving.has(id); });
}

function sumTargetFor(msg, sender) {
    if (!sumBusy.size) return null;
    const urls = [sender && sender.tab && sender.tab.url, msg && msg.url].filter(Boolean).map(u => normalizeUrl(u));
    for (const [id, st] of sumBusy) if (!st.queued && urls.includes(st.key)) return id;
    const live = [...sumBusy].filter(([, st]) => !st.queued);
    return live.length === 1 && sender && sender.tab ? live[0][0] : null;   // redirected page: a single running one is ours
}
function onQueueUpdate(msg) {
    const waiting = new Map((msg.queue || []).map(j => [j.id, j]));
    for (const [id, st] of [...sumBusy]) {
        if (st.jobId == null) continue;
        if (waiting.has(st.jobId)) { if (!st.queued) { st.queued = true; armSum(id, 60 * 60 * 1000); paintSum(id); } }
        else if (st.queued) {
            const running = msg.running && msg.running.id === st.jobId;
            st.queued = false; st.pct = 5; armSum(id, 15 * 60 * 1000);
            if (running) paintSum(id); else endSum(id);
        }
    }
}
function onSummaryMessage(msg, sender) {
    if (msg && msg.action === 'summaryQueue') return onQueueUpdate(msg);
    if (!msg || !['summaryProgress', 'summaryComplete', 'summaryError'].includes(msg.action)) return;
    const id = sumTargetFor(msg, sender); if (!id) return;
    const st = sumBusy.get(id); if (!st) return;
    if (msg.action === 'summaryProgress') {
        if (typeof msg.progress === 'number' && msg.progress > st.pct) { st.pct = Math.min(99, msg.progress); paintSum(id); }
    } else if (msg.action === 'summaryComplete') {
        st.pct = 100; paintSum(id);
        setTimeout(async () => { endSum(id); await manager.resolve(id); await renderList(); }, 400);   // it now lives in History
    } else {
        endSum(id);
        sumErrors.set(id, msg.error || T('Failed'));
        renderList();
    }
}

// Open the link in a new tab (it stays in the list: you may still want to summarize or save it afterwards).
function openLink(entry) {
    if (!/^https?:\/\//i.test(entry.url)) return;
    try { if (chrome.tabs && chrome.tabs.create) { chrome.tabs.create({ url: entry.url }); return; } } catch (_) { /* fall back below */ }
    window.open(entry.url, '_blank', 'noopener');
}
async function dismiss(entry) { await manager.resolve(entry.id); await renderList(); }

// A summary can finish while the popup is closed (it runs in the background): any waiting link that has an article in
// History saved after the link arrived counts as summarized and is taken off the list (and deleted on the server).
async function resolveSummarized() {
    const waiting = await manager.listPending();
    if (!waiting.length) return;
    let index = [];
    try { index = (await chrome.storage.local.get(SK.articlesIndex))[SK.articlesIndex] || []; } catch (_) { return; }
    const saved = new Map();
    for (const a of index) {
        if (!a || !a.url) continue;
        const t = Date.parse(a.timestamp) || 0;
        for (const u of [a.url, a.feedUrl]) {   // feedUrl: the link the page was opened from (it may have redirected)
            if (!u) continue;
            const k = normalizeUrl(u);
            if (t > (saved.get(k) || 0)) saved.set(k, t);
        }
    }
    for (const e of waiting) {
        if (sumBusy.has(e.id)) continue;   // its own completion handler deals with it
        const t = saved.get(normalizeUrl(e.url));
        if (t && t >= (e.receivedAt || 0)) await manager.resolve(e.id);
    }
}

async function renderList() {
    const root = $('phoneInbox');
    if (!root) return;
    try { await resolveSummarized(); } catch (_) { /* the list still renders */ }
    const list = await manager.listPending();
    root.hidden = !list.length;
    root.textContent = '';
    if (!list.length) return;
    const head = document.createElement('h4'); head.className = 'phone-inbox-head'; head.textContent = T('From phone') + ' · ' + list.length;
    root.append(head);
    for (const entry of list) {
        const { host, path } = shortLink(entry.url);
        const row = document.createElement('div'); row.className = 'phone-inbox-item';
        const text = document.createElement('a'); text.className = 'phone-inbox-link';
        if (/^https?:\/\//i.test(entry.url)) { text.href = entry.url; text.target = '_blank'; text.rel = 'noopener noreferrer'; }
        const h = document.createElement('strong'); h.textContent = host;
        const p = document.createElement('span'); p.textContent = path.length > 60 ? path.slice(0, 59) + '…' : path;
        text.append(h, p); text.title = entry.url;
        const sum = button('', 'button-primary btn-sm feed-sum-btn', () => summarize(entry));
        sum.dataset.id = entry.id; setLabel(sum, T('✨ Summarize'));
        const open = button(T('Open ↗'), 'button-secondary btn-sm phone-inbox-open', () => openLink(entry));
        const save = button('', 'button-secondary btn-sm phone-inbox-save', () => saveOnly(entry));
        save.dataset.id = entry.id; save.title = T('Keep it in History, no AI, nothing sent'); setIconLabel(save, 'download', T('Save only'));
        row.append(text, open, sum, save, button(T('Dismiss'), 'button-tertiary btn-sm', () => dismiss(entry)));
        root.append(row);
        if (sumErrors.has(entry.id)) {
            const err = para(sumErrors.get(entry.id), 'phone-inbox-error'); err.dataset.id = entry.id; err.setAttribute('role', 'alert');
            root.append(err);
        }
        paintSum(entry.id); paintSaving(entry.id);
    }
}

export async function initInboxView() {
    try { if (chrome.runtime.onMessage && chrome.runtime.onMessage.addListener) chrome.runtime.onMessage.addListener(onSummaryMessage); } catch (_) { /* no runtime */ }
    await Promise.all([renderSettings(), renderList()]);
    chrome.storage.onChanged.addListener((changes, ns) => {
        if (ns !== 'local') return;
        if (changes[SK.inboxPending]) renderList();
        if (changes[SK.inboxPending] || changes[SK.inboxState] || changes[SK.inboxConfig]) renderSettings();
    });
    // collect whatever the phone shared since the popup was last open
    manager.poll().then(() => { renderList(); renderSettings(); }).catch(() => {});
}
